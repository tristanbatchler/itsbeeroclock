type CatalogueItem struct {
	PK      string  `dynamodbav:"PK"`     // CATALOGUE
	SK      string  `dynamodbav:"SK"`     // BEER#{id}
	GSI1PK  string  `dynamodbav:"GSI1PK"` // CATALOGUE
	GSI1SK  string  `dynamodbav:"GSI1SK"` // {brewery}#{name}
	BeerID  string  `dynamodbav:"BeerID"`
	Name    string  `dynamodbav:"Name"`
	Brewery string  `dynamodbav:"Brewery"`
	ABV     float64 `dynamodbav:"ABV"`
	Image   string  `dynamodbav:"Image"`
	Rank    int     `dynamodbav:"Rank"`
}

// beers.json is generated by tools/catalogue/build.py.
//
//go:embed beers.json
var beersJSON []byte

type seedBeer struct {
	ID      string  `json:"id"`
	Name    string  `json:"name"`
	Brewery string  `json:"brewery"`
	ABV     float64 `json:"abv"`
	Image   string  `json:"image"`
	Rank    int     `json:"rank"`
}

// createLocalTable mirrors BeerTable in infra/cdk/lib/cdk-stack.ts.
func createLocalTable(ctx context.Context, db *dynamodb.Client) error {
	stringAttr := func(name string) types.AttributeDefinition {
		return types.AttributeDefinition{AttributeName: aws.String(name), AttributeType: types.ScalarAttributeTypeS}
	}
	keys := func(partition, sort string) []types.KeySchemaElement {
		return []types.KeySchemaElement{
			{AttributeName: aws.String(partition), KeyType: types.KeyTypeHash},
			{AttributeName: aws.String(sort), KeyType: types.KeyTypeRange},
		}
	}
	allAttrs := &types.Projection{ProjectionType: types.ProjectionTypeAll}

	_, err := db.CreateTable(ctx, &dynamodb.CreateTableInput{
		TableName:   beerAws.TableName(),
		BillingMode: types.BillingModePayPerRequest,
		AttributeDefinitions: []types.AttributeDefinition{
			stringAttr("PK"),
			stringAttr("SK"),
			stringAttr("GSI1PK"),
			stringAttr("GSI1SK"),
			{AttributeName: aws.String("Timestamp"), AttributeType: types.ScalarAttributeTypeN},
		},
		KeySchema: keys("PK", "SK"),
		GlobalSecondaryIndexes: []types.GlobalSecondaryIndex{
			{IndexName: aws.String("GSI1"), KeySchema: keys("GSI1PK", "GSI1SK"), Projection: allAttrs},
			{IndexName: aws.String("GSI2"), KeySchema: keys("PK", "Timestamp"), Projection: allAttrs},
		},
	})
	var exists *types.ResourceInUseException
	if errors.As(err, &exists) {
		return nil
	}
	return err
}

func main() {
	prod := flag.Bool("prod", false, "write to the real DynamoDB table instead of DynamoDB Local")
	prune := flag.Bool("prune", false, "after writing, report catalogue rows that aren't in beers.json")
	execute := flag.Bool("execute", false, "with -prune, really delete those rows")
	flag.Parse()
	beerAws.RequireLocalDynamoDB(*prod)

	db, err := beerAws.NewDynamoClient(context.Background())
	if err != nil {
		log.Fatal(err)
	}
	if beerAws.LocalDynamoDBEndpoint() != "" {
		if err := createLocalTable(context.Background(), db); err != nil {
			log.Fatal(err)
		}
	}

	var beers []seedBeer
	if err := json.Unmarshal(beersJSON, &beers); err != nil {
		log.Fatal(err)
	}

	writes := make([]types.WriteRequest, 0, len(beers))
	for _, b := range beers {
		item := CatalogueItem{
			PK:      "CATALOGUE",
			SK:      fmt.Sprintf("BEER#%s", b.ID),
			GSI1PK:  "CATALOGUE",
			GSI1SK:  fmt.Sprintf("%s#%s", b.Brewery, b.Name),
			BeerID:  b.ID,
			Name:    b.Name,
			Brewery: b.Brewery,
			ABV:     b.ABV,
			Image:   b.Image,
			Rank:    b.Rank,
		}

		av, err := attributevalue.MarshalMap(item)
		if err != nil {
			log.Fatalf("Error marshalling %s: %v", b.Name, err)
		}
		writes = append(writes, types.WriteRequest{PutRequest: &types.PutRequest{Item: av}})
	}

	if err := writeAll(context.Background(), db, writes); err != nil {
		log.Fatal(err)
	}
	log.Printf("Seed complete! Wrote %d beers", len(writes))

	if *prune {
		if err := pruneCatalogue(context.Background(), db, beers, *execute); err != nil {
			log.Fatal(err)
		}
	}
}

// staleRows returns catalogue keys for beers no longer in beers.json. A drink logged
// against one counts as no alcohol, so it also counts the drink records affected.
func staleRows(items []map[string]types.AttributeValue, beers []seedBeer) (stale []map[string]types.AttributeValue, affectedDrinks int) {
	current := make(map[string]bool, len(beers))
	for _, b := range beers {
		current[fmt.Sprintf("BEER#%s", b.ID)] = true
	}
	removed := make(map[string]bool)
	for _, item := range items {
		pk, _ := item["PK"].(*types.AttributeValueMemberS)
		sk, _ := item["SK"].(*types.AttributeValueMemberS)
		if pk != nil && sk != nil && pk.Value == beerAws.KeyCatalog && !current[sk.Value] {
			stale = append(stale, map[string]types.AttributeValue{"PK": pk, "SK": sk})
			removed[strings.TrimPrefix(sk.Value, "BEER#")] = true
		}
	}
	for _, item := range items {
		pk, _ := item["PK"].(*types.AttributeValueMemberS)
		id, _ := item["BeerID"].(*types.AttributeValueMemberS)
		if pk != nil && id != nil && strings.HasPrefix(pk.Value, beerAws.PrefixUser) && removed[id.Value] {
			affectedDrinks++
		}
	}
	return stale, affectedDrinks
}

func pruneCatalogue(ctx context.Context, db *dynamodb.Client, beers []seedBeer, execute bool) error {
	var items []map[string]types.AttributeValue
	input := &dynamodb.ScanInput{
		TableName:                beerAws.TableName(),
		ProjectionExpression:     aws.String("#pk, #sk, BeerID"),
		ExpressionAttributeNames: map[string]string{"#pk": "PK", "#sk": "SK"},
	}
	for {
		out, err := db.Scan(ctx, input)
		if err != nil {
			return err
		}
		items = append(items, out.Items...)
		if len(out.LastEvaluatedKey) == 0 {
			break
		}
		input.ExclusiveStartKey = out.LastEvaluatedKey
	}

	stale, affectedDrinks := staleRows(items, beers)
	log.Printf("%d catalogue rows aren't in beers.json; %d logged drinks reference them", len(stale), affectedDrinks)
	if !execute {
		log.Print("Dry run: pass -execute to delete them")
		return nil
	}
	writes := make([]types.WriteRequest, 0, len(stale))
	for _, key := range stale {
		writes = append(writes, types.WriteRequest{DeleteRequest: &types.DeleteRequest{Key: key}})
	}
	if err := writeAll(ctx, db, writes); err != nil {
		return err
	}
	log.Printf("Deleted %d catalogue rows", len(writes))
	return nil
}

// writeAll sends writes in DynamoDB's batches of 25, resending anything it throttles.
func writeAll(ctx context.Context, db *dynamodb.Client, writes []types.WriteRequest) error {
	table := *beerAws.TableName()
	const batchSize, maxRetries = 25, 8
	for len(writes) > 0 {
		batch := writes[:min(batchSize, len(writes))]
		writes = writes[len(batch):]
		for attempt := 0; len(batch) > 0; attempt++ {
			if attempt == maxRetries {
				return fmt.Errorf("gave up with %d writes unprocessed", len(batch))
			}
			if attempt > 0 {
				time.Sleep(time.Duration(1<<attempt) * 100 * time.Millisecond)
			}
			out, err := db.BatchWriteItem(ctx, &dynamodb.BatchWriteItemInput{
				RequestItems: map[string][]types.WriteRequest{table: batch},
			})
			if err != nil {
				return err
			}
			batch = out.UnprocessedItems[table]
		}
	}
	return nil
}
